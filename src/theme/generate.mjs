import fs from 'node:fs';
import { contrast, parseHex, sameRgb, toHex, toTriplet } from './color.mjs';
import { enforceContrast, contrastReport } from './contrast.mjs';
import { makeTransforms, radiusPx } from './palette.mjs';

export const HEADER_MARK = '/* kette theme ';
export const RADIUS_NAMES = { none: 0, sm: 4, md: 8, lg: 12 };
export const NEUTRAL_NAMES = ['cool', 'warm', 'neutral'];
const NAME = /^[a-z0-9][a-z0-9-]{0,39}$/;
const MAX_RADIUS_PX = 64;
const FONT_FORBIDDEN = /[;{}<>\\`\u0000-\u001f]/;
const GENERIC_FAMILIES = new Set(['serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui', 'ui-sans-serif', 'ui-serif', 'ui-monospace']);
export const EDITION_NOTE = 'Community generates this theme.css on top of the token system. Enterprise extends the token source itself in @getitdone-gmbh/kette-tokens: several brands, component tokens and Figma variables synced to code.';

let cached = null;
export function loadManifest() {
  cached ??= JSON.parse(fs.readFileSync(new URL('./manifest.json', import.meta.url), 'utf8'));
  return cached;
}

const fail = (message) => {
  const err = new Error(message);
  err.usage = true;
  return err;
};

function hexOption(flag, value) {
  try {
    return parseHex(value);
  } catch {
    throw fail(`${flag} needs a hex colour like #0f766e, got ${JSON.stringify(value)}`);
  }
}

// Font stack from one family or a comma list; names with spaces are quoted, a generic fallback is added when none is given
export function fontStack(input) {
  const families = String(input).split(',').map((f) => f.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
  if (!families.length || families.some((f) => FONT_FORBIDDEN.test(f) || /["']/.test(f)) || String(input).length > 200) {
    throw fail(`--font needs a font family like "Inter" or "IBM Plex Sans, sans-serif", got ${JSON.stringify(input)}`);
  }
  const quoted = families.map((f) => (GENERIC_FAMILIES.has(f) || /^[A-Za-z-]+$/.test(f) ? f : `"${f}"`));
  return families.some((f) => GENERIC_FAMILIES.has(f)) ? quoted.join(', ') : [...quoted, 'system-ui', 'sans-serif'].join(', ');
}

// Validated generator inputs from raw flag values; wrong values throw an error marked usage (exit code 2 in the CLI)
export function parseThemeOptions(raw) {
  if (!raw.primary) throw fail('--primary is required, for example --primary "#0f766e"');
  const primary = hexOption('--primary', raw.primary);
  const accent = raw.accent ? hexOption('--accent', raw.accent) : null;
  const neutralRaw = String(raw.neutral || 'cool').toLowerCase();
  const neutral = NEUTRAL_NAMES.includes(neutralRaw) ? neutralRaw : hexOption('--neutral (warm, cool, neutral or a hex colour)', neutralRaw);
  const radiusRaw = String(raw.radius ?? 'md').toLowerCase();
  let radius;
  if (radiusRaw === 'full') radius = 'full';
  else if (Object.hasOwn(RADIUS_NAMES, radiusRaw)) radius = RADIUS_NAMES[radiusRaw];
  else if (/^\d+(px)?$/.test(radiusRaw) && parseInt(radiusRaw, 10) <= MAX_RADIUS_PX) radius = parseInt(radiusRaw, 10);
  else throw fail(`--radius needs none, sm, md, lg, full or pixels from 0 to ${MAX_RADIUS_PX}, got ${JSON.stringify(raw.radius)}`);
  const font = raw.font ? fontStack(raw.font) : null;
  const name = raw.name || `custom-${toHex(primary).slice(1)}`;
  if (!NAME.test(name)) throw fail(`--name needs lowercase letters, digits and dashes (at most 40), got ${JSON.stringify(name)}`);
  return { primary, accent, neutral, radius, font, name };
}

export const describeInputs = (o) => ({
  primary: toHex(o.primary),
  accent: o.accent ? toHex(o.accent) : null,
  neutral: typeof o.neutral === 'string' ? o.neutral : toHex(o.neutral),
  radius: typeof o.radius === 'number' ? `${o.radius}px` : o.radius,
  font: o.font,
});

// Best on-colour for a fill the theme leaves undefined: white or the darkest neutral, whichever contrasts more
function onColour(fill, toNeutral) {
  const dark = toNeutral([2, 6, 23]);
  return contrast(fill, [255, 255, 255]) >= contrast(fill, dark) ? [255, 255, 255] : dark;
}

function header(options, manifest, version, summary) {
  const inputs = Object.entries(describeInputs(options)).filter(([, v]) => v !== null).map(([k, v]) => `--${k} ${v}`).join(' ');
  return [
    `${HEADER_MARK}"${options.name}", generated by kette-cli ${version} (${inputs}).`,
    `   Drop-in replacement for @import '@getitdone-gmbh/kette-design-community/theme.css', variable set of ${manifest.source.theme}.`,
    `   WCAG AA: ${summary.checks} fill/text pairs per mode at 4.5:1 (focus indicators 3:1), ${summary.adjusted} values adjusted.`,
    `   ${EDITION_NOTE} */`,
  ].join('\n');
}

// The whole theme for one set of inputs: CSS, values per mode, palettes, contrast report and adjustments. Same inputs, same output.
export function generateTheme(options, { manifest = loadManifest(), version = '0.0.0' } = {}) {
  const t = makeTransforms(options, manifest.anchors);
  const values = { light: {}, dark: {} };
  for (const [name, spec] of Object.entries(manifest.colors)) {
    for (const mode of ['light', 'dark']) if (spec[mode]) values[mode][name] = t.apply(spec[mode][3], spec[mode].slice(0, 3));
  }
  for (const [text, fill] of Object.entries(manifest.pairOn)) {
    for (const mode of ['light', 'dark']) values[mode][text] = onColour(values[mode][fill], t.toNeutral);
  }
  const adjustments = ['light', 'dark'].flatMap((mode) => enforceContrast(values[mode], manifest.checks, mode));
  const checks = ['light', 'dark'].flatMap((mode) => contrastReport(values[mode], manifest.checks, mode));
  const basePx = manifest.radius['--borderRadius']?.px || RADIUS_NAMES.md;
  const radius = Object.fromEntries(Object.entries(manifest.radius).map(([n, e]) => [n, `${radiusPx(e, options.radius, basePx)}px`]));
  const font = options.font || manifest.font;
  const shadows = Object.fromEntries(Object.entries(manifest.shadows).map(([n, v]) => [n, t.shadow(v)]));
  // Variables the dark blocks inherit from :root are pinned there when contrast gave them their own dark value
  const darkPins = Object.entries(manifest.colors).filter(([n, spec]) => spec.inherit && !sameRgb(values.dark[n], values.light[n])).map(([n]) => n);
  const pinned = manifest.template.replace(/^(\s*)\{\{pins:dark\}\}\n/gm, (_, indent) => darkPins.map((n) => `${indent}${n}: ${toTriplet(values.dark[n])};\n`).join(''));
  const body = pinned.replace(/\{\{([^}]+)\}\}/g, (_, key) => {
    const [kind, a, b] = key.split(':');
    if (kind === 'c') return toTriplet(values[a][b]);
    if (kind === 'radius') return radius[a];
    if (kind === 'shadow') return shadows[a];
    if (kind === 'font') return font;
    throw new Error(`Unknown placeholder in the theme manifest: ${key}`);
  });
  const summary = { checks: manifest.checks.length, adjusted: adjustments.length };
  const css = `${header(options, manifest, version, summary)}\n\n${body.replace(/\s*$/, '\n')}`;
  const hexes = (mode) => Object.fromEntries(Object.entries(values[mode]).sort(([a], [b]) => a.localeCompare(b)).map(([n, rgb]) => [n, toHex(rgb)]));
  const tokens = {
    name: options.name,
    generator: `kette-cli ${version}`,
    source: manifest.source,
    inputs: describeInputs(options),
    palettes: Object.fromEntries(Object.entries(t.palettes).map(([k, ramp]) => [k, Object.fromEntries(ramp.map((rgb, i) => [manifest.anchors.steps[i], toHex(rgb)]))])),
    light: hexes('light'),
    dark: hexes('dark'),
    radius,
    font,
    shadows,
    contrast: { checked: checks.length, failing: checks.filter((c) => !c.pass).length },
    checks,
    adjustments: adjustments.map((a) => ({ ...a, before: Math.floor(a.before * 100) / 100, after: Math.floor(a.after * 100) / 100 })),
    editions: EDITION_NOTE,
  };
  return { css, tokens, values };
}
