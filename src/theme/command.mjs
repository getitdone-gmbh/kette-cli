import fs from 'node:fs';
import path from 'node:path';
import { ask, confirm } from '../prompt.mjs';
import { openBrowser, openerForFile } from '../cloud.mjs';
import { cmd, dim, file, status } from '../out.mjs';
import { ExitError } from '../errors.mjs';
import { parseHex } from './color.mjs';
import { EDITION_NOTE, HEADER_MARK, NEUTRAL_NAMES, RADIUS_NAMES, describeInputs, fontStack, generateTheme, parseThemeOptions } from './generate.mjs';
import { PREVIEW_MARK, previewHtml } from './preview.mjs';
import { writeAtomic } from '../files.mjs';

export const DEFAULT_OUT = 'theme.css';
export const PREVIEW_FILE = 'theme-preview.html';
const COMMUNITY_IMPORT = "@import '@getitdone-gmbh/kette-design-community/theme.css'";
const ATTEMPTS = 3;

const line = (kind, text) => console.log(`${status(kind, { ok: 'OK  ', warn: 'WARN', info: 'INFO' }[kind])} ${text}`);

// Target file: --out as given, inside it when it is a folder (existing, or written with a trailing slash)
export function outputPaths(out = DEFAULT_OUT, cwd = process.cwd()) {
  const target = path.resolve(cwd, out);
  const isDir = /[\\/]$/.test(out) || (fs.existsSync(target) && fs.statSync(target).isDirectory());
  const css = isDir ? path.join(target, DEFAULT_OUT) : target;
  return { css, preview: path.join(path.dirname(css), PREVIEW_FILE) };
}

async function askValid(question, fallback, check) {
  for (let i = 0; i < ATTEMPTS; i++) {
    const answer = await ask(question, fallback);
    try {
      check(answer);
      return answer;
    } catch (err) {
      console.log(`  ${err.message}`);
    }
  }
  throw new ExitError(`No valid answer for: ${question}`);
}

const optionalHex = (s) => s === '' || parseHex(s);
const neutralValue = (s) => NEUTRAL_NAMES.includes(s.toLowerCase()) || parseHex(s);
const radiusValue = (s) => {
  if (!(s === 'full' || Object.hasOwn(RADIUS_NAMES, s) || /^\d+(px)?$/.test(s))) throw new Error('none, sm, md, lg, full or a number of pixels');
};

// Questions for every option the flags left open; Enter keeps the shown default
async function interactive(raw) {
  const primary = await askValid('Primary colour (hex)', '', (s) => parseHex(s));
  const accent = raw.accent ?? (await askValid('Accent colour (hex, empty for none)', '', optionalHex));
  const neutral = raw.neutral ?? (await askValid('Neutral (cool, warm, neutral or hex)', 'cool', neutralValue));
  const radius = raw.radius ?? (await askValid('Corner radius (none, sm, md, lg, full or px)', 'md', radiusValue));
  const font = raw.font ?? (await askValid('Font family (empty keeps Inter)', '', (s) => s === '' || fontStack(s)));
  const name = raw.name ?? (await ask('Theme name', `custom-${parseHex(primary).map((x) => x.toString(16).padStart(2, '0')).join('')}`));
  const out = raw.out ?? (await ask('Output file', DEFAULT_OUT));
  const preview = raw.preview || (await confirm('Write a preview page next to it?'));
  return { ...raw, primary, accent: accent || null, neutral, radius, font: font || null, name, out, preview };
}

// A file kette theme did not write is only replaced after a yes (question in a terminal, --yes otherwise)
async function guardOverwrite(target, mark, { yes, tty }) {
  if (yes || !fs.existsSync(target) || fs.readFileSync(target, 'utf8').includes(mark)) return;
  if (tty && (await confirm(`${target} was not generated by kette theme. Replace it?`))) return;
  throw new ExitError(`${target} exists and was not generated by kette theme. Use --out for another file or --yes to replace it.`, 1);
}

function report(result, paths, opts) {
  const { tokens } = result;
  const inputs = describeInputs(result.options);
  const verb = opts.dryRun ? 'Would write' : 'Wrote';
  line('ok', `Theme "${tokens.name}": primary ${inputs.primary}${inputs.accent ? `, accent ${inputs.accent}` : ''}, neutral ${inputs.neutral}, radius ${inputs.radius}${inputs.font ? `, font ${inputs.font}` : ''}`);
  line('ok', `${verb} ${file(paths.css)}`);
  if (opts.preview) line('ok', `${verb} ${file(paths.preview)}`);
  line('ok', `WCAG AA: ${tokens.contrast.checked} checks in light and dark (text 4.5:1, focus indicators 3:1), none failing`);
  if (tokens.adjustments.length) {
    line('info', `Adjusted ${tokens.adjustments.length} value${tokens.adjustments.length === 1 ? '' : 's'} to reach the minimum contrast:`);
    for (const a of tokens.adjustments) console.log(`       ${a.mode.padEnd(5)} ${a.name} ${a.from} -> ${a.to} ${dim(`(${a.check}, ${a.before.toFixed(2)}:1 -> ${a.after.toFixed(2)}:1)`)}`);
  }
  console.log('');
  console.log(`Use it instead of ${cmd(COMMUNITY_IMPORT)}: ${cmd(`@import './${path.basename(paths.css)}'`)}`);
  if (inputs.font) console.log(`Load the font ${inputs.font} yourself (for example with @font-face), the theme only names it.`);
  console.log(dim(`${EDITION_NOTE} Enterprise: kette login.`));
  if (opts.dryRun) console.log(dim('Dry run, nothing written.'));
}

// kette theme: flags, or questions in a terminal when --primary is missing; --json prints the tokens instead of the report
export async function theme(opts, { version, tty = Boolean(process.stdin.isTTY && process.stdout.isTTY), cwd = process.cwd(), open = (f) => openBrowser(f, { openerOf: openerForFile }) } = {}) {
  let raw = { primary: opts.primary, accent: opts.accent, neutral: opts.neutral, radius: opts.radius, font: opts.font, name: opts.name, out: opts.out, preview: Boolean(opts.preview) };
  if (!raw.primary) {
    if (!tty || opts.json || opts.yes) throw new ExitError('--primary is required without a terminal, for example: kette theme --primary "#0f766e"');
    raw = await interactive(raw);
  }
  let options;
  try {
    options = parseThemeOptions(raw);
  } catch (err) {
    if (err.usage) throw new ExitError(err.message);
    throw err;
  }
  const result = { ...generateTheme(options, { version }), options };
  const paths = outputPaths(raw.out, cwd);
  if (!opts.dryRun) {
    await guardOverwrite(paths.css, HEADER_MARK, { yes: opts.yes, tty });
    if (raw.preview) await guardOverwrite(paths.preview, PREVIEW_MARK, { yes: opts.yes, tty });
    fs.mkdirSync(path.dirname(paths.css), { recursive: true });
    writeAtomic(paths.css, result.css);
    if (raw.preview) writeAtomic(paths.preview, previewHtml(result));
  }
  if (opts.json) {
    const json = JSON.stringify({ ...result.tokens, files: { css: paths.css, preview: raw.preview ? paths.preview : null }, written: !opts.dryRun }, null, 2);
    // The CLI exits right after the command; waiting for the write keeps a piped JSON (over 64 KB) from being cut off
    await new Promise((resolve) => process.stdout.write(`${json}\n`, resolve));
    return 0;
  }
  report(result, paths, { dryRun: opts.dryRun, preview: raw.preview });
  if (raw.preview && !opts.dryRun && tty && !open(paths.preview)) console.log(`Open the preview: ${file(paths.preview)}`);
  return 0;
}
